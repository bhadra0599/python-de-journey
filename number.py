a = 7
b = 3

print(a+b)      #addition
print(a-b)      #sub
print(a*b)      #multiplication
print(a/b)      #division
print(a//b)     #output : 2 (7/3 = 2.33)
print(a**b)     #power
print(a%b)      #modulus or remainder

#comparsions
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

